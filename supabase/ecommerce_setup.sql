update public.products
set name_uz = coalesce(nullif(name_uz, ''), "Name"),
    name_ru = coalesce(nullif(name_ru, ''), "Name")
where name_uz is null or name_uz = '' or name_ru is null or name_ru = '';

create index if not exists products_category_idx on public.products (category);
create index if not exists products_featured_idx on public.products (featured) where featured;
create index if not exists products_created_at_idx on public.products (created_at desc);

-- ----------------------------------------------------------------------------
--  2. ADMIN AUTHORIZATION
-- ----------------------------------------------------------------------------

create or replace function public.is_store_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.store_admins
    where lower(email) = lower(auth.jwt() ->> 'email')
  );
$$;

revoke all on function public.is_store_admin() from public;
grant execute on function public.is_store_admin() to authenticated;

alter table public.store_admins enable row level security;
revoke all on public.store_admins from anon, authenticated;

