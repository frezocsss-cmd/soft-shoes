-- ----------------------------------------------------------------------------
--  5. ORDERS
-- ----------------------------------------------------------------------------

create sequence if not exists public.order_number_seq;

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  order_number text not null unique,
  customer_name text not null,
  customer_phone text not null,
  customer_telegram text,
  address text not null default '',
  comment text,
  fulfillment text not null default 'delivery'
    check (fulfillment in ('delivery', 'pickup')),
  status text not null default 'new'
    check (status in ('new', 'confirmed', 'shipped', 'completed', 'cancelled')),
  total numeric(12, 2) not null default 0 check (total >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders (id) on delete cascade,
  product_id bigint references public.products (id) on delete set null,
  product_name text not null,
  product_image text,
  size integer,
  unit_price numeric(12, 2) not null check (unit_price >= 0),
  quantity integer not null check (quantity > 0),
  line_total numeric(12, 2) not null check (line_total >= 0)
);

create index if not exists orders_created_at_idx on public.orders (created_at desc);
create index if not exists orders_status_idx on public.orders (status);
create index if not exists order_items_order_id_idx on public.order_items (order_id);

create or replace function public.touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists orders_touch_updated_at on public.orders;
create trigger orders_touch_updated_at
before update on public.orders
for each row execute function public.touch_updated_at();

alter table public.orders enable row level security;
alter table public.order_items enable row level security;

revoke all on public.orders from anon, authenticated;
revoke all on public.order_items from anon, authenticated;

grant select, update on public.orders to authenticated;
grant select on public.order_items to authenticated;

drop policy if exists "orders_admin_read" on public.orders;
drop policy if exists "orders_admin_update" on public.orders;
drop policy if exists "orders_admin_delete" on public.orders;
drop policy if exists "order_items_admin_read" on public.order_items;

create policy "orders_admin_read"
on public.orders for select to authenticated
using (public.is_store_admin());

create policy "orders_admin_update"
on public.orders for update to authenticated
using (public.is_store_admin())
with check (public.is_store_admin());

create policy "orders_admin_delete"
on public.orders for delete to authenticated
using (public.is_store_admin());

create policy "order_items_admin_read"
on public.order_items for select to authenticated
using (public.is_store_admin());

grant delete on public.orders to authenticated;

-- ----------------------------------------------------------------------------
--  6. SECURE ORDER CREATION
--
--  The browser sends only product ids, sizes and quantities. Prices, names,
--  stock validation and totals are read and calculated inside PostgreSQL.
-- ----------------------------------------------------------------------------

create or replace function public.create_order(p_customer jsonb, p_items jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order public.orders%rowtype;
  v_product public.products%rowtype;
  v_item jsonb;
  v_item_count integer;
  v_quantity integer;
  v_size integer;
  v_price numeric(12, 2);
  v_line_total numeric(12, 2);
  v_total numeric(12, 2) := 0;
  v_customer_name text;
  v_customer_phone text;
  v_customer_telegram text;
  v_address text;
  v_comment text;
  v_fulfillment text;
  v_order_number text;
  v_product_name text;
begin
  if p_customer is null or jsonb_typeof(p_customer) <> 'object' then
    raise exception 'INVALID_CUSTOMER' using errcode = '22023';
  end if;

  v_customer_name := nullif(trim(p_customer ->> 'name'), '');
  v_customer_phone := nullif(trim(p_customer ->> 'phone'), '');
  v_customer_telegram := nullif(trim(p_customer ->> 'telegram'), '');
  v_address := coalesce(trim(p_customer ->> 'address'), '');
  v_comment := nullif(trim(p_customer ->> 'comment'), '');
  v_fulfillment := coalesce(nullif(trim(p_customer ->> 'fulfillment'), ''), 'delivery');

  if v_customer_name is null then
    raise exception 'CUSTOMER_NAME_REQUIRED' using errcode = '22023';
  end if;
  if v_customer_phone is null or length(v_customer_phone) < 7 then
    raise exception 'CUSTOMER_PHONE_REQUIRED' using errcode = '22023';
  end if;
  if v_fulfillment not in ('delivery', 'pickup') then
    v_fulfillment := 'delivery';
  end if;
  if v_fulfillment = 'delivery' and v_address = '' then
    raise exception 'DELIVERY_ADDRESS_REQUIRED' using errcode = '22023';
  end if;

  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'EMPTY_ORDER' using errcode = '22023';
  end if;

  v_item_count := jsonb_array_length(p_items);
  if v_item_count > 50 then
    raise exception 'TOO_MANY_ITEMS' using errcode = '22023';
  end if;

  v_order_number := 'SS-' || to_char(now(), 'YYMMDD') || '-' ||
    lpad(nextval('public.order_number_seq')::text, 5, '0');

  insert into public.orders (
    order_number, customer_name, customer_phone, customer_telegram,
    address, comment, fulfillment, status, total
  )
  values (
    v_order_number, v_customer_name, v_customer_phone, v_customer_telegram,
    v_address, v_comment, v_fulfillment, 'new', 0
  )
  returning * into v_order;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    if jsonb_typeof(v_item) <> 'object' then
      raise exception 'INVALID_ITEM' using errcode = '22023';
    end if;

    begin
      v_quantity := floor((v_item ->> 'quantity')::numeric)::integer;
      v_size := nullif(trim(v_item ->> 'size'), '')::integer;
    exception
      when others then
        raise exception 'INVALID_QUANTITY_OR_SIZE' using errcode = '22023';
    end;

    if v_quantity is null or v_quantity < 1 or v_quantity > 50 then
      raise exception 'INVALID_QUANTITY' using errcode = '22023';
    end if;

    if (v_item ->> 'product_id') is null then
      raise exception 'PRODUCT_REQUIRED' using errcode = '22023';
    end if;

    select * into v_product
    from public.products
    where id = (v_item ->> 'product_id')::bigint
    for update;

    if not found then
      raise exception 'PRODUCT_NOT_FOUND' using errcode = 'P0002';
    end if;

    if v_size is not null
       and coalesce(array_length(v_product.sizes, 1), 0) > 0
       and not (v_size = any (v_product.sizes)) then
      raise exception 'INVALID_SIZE' using errcode = '22023';
    end if;

    v_price := v_product."Price";
    if v_price is null or v_price <= 0 then
      raise exception 'INVALID_PRODUCT_PRICE' using errcode = '22023';
    end if;

    if v_product.stock is not null then
      if v_product.stock < v_quantity then
        raise exception 'INSUFFICIENT_STOCK' using errcode = 'P0001';
      end if;

      update public.products
      set stock = stock - v_quantity
      where id = v_product.id;
    end if;

    v_line_total := v_price * v_quantity;
    v_total := v_total + v_line_total;

    v_product_name := coalesce(
      nullif(v_product.name_uz, ''),
      nullif(v_product."Name", ''),
      nullif(v_product.name_ru, ''),
      'Mahsulot'
    );

    insert into public.order_items (
      order_id, product_id, product_name, product_image, size,
      unit_price, quantity, line_total
    )
    values (
      v_order.id, v_product.id, v_product_name, v_product.image_url, v_size,
      v_price, v_quantity, v_line_total
    );
  end loop;

  update public.orders
  set total = v_total
  where id = v_order.id
  returning * into v_order;

  return jsonb_build_object(
    'id', v_order.id,
    'order_number', v_order.order_number,
    'status', v_order.status,
    'total', v_order.total,
    'created_at', v_order.created_at
  );
end;
$$;

revoke all on function public.create_order(jsonb, jsonb) from public;
grant execute on function public.create_order(jsonb, jsonb) to anon, authenticated;

